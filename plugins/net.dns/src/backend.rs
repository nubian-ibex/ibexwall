//! Which DNS stack the machine uses, read from the system without
//! changing anything. An unsupported or unclear stack is refused with a
//! reason instead of guessed.

use std::collections::BTreeMap;

use ibexwall_proto::names;
use ibexwall_sdk::Sandbox;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Backend {
    /// `/etc/resolv.conf` is managed by systemd-resolved. NetworkManager
    /// or systemd-networkd may feed it per-link servers; their interplay
    /// is handled in a later step (spike S3-b/c).
    Resolved,
    /// NetworkManager writes `/etc/resolv.conf` itself (ADR-0051).
    NetworkManager,
    /// Not supported yet.
    Unsupported(&'static str),
}

const NOT_SUPPORTED: &str = "this DNS configuration is not supported yet";

/// Where systemd records that a unit is running.
pub fn running(sandbox: &Sandbox, unit: &str) -> bool {
    sandbox.has_entry(&format!("/run/systemd/units/invocation:{unit}"))
}

pub fn detect(sandbox: &Sandbox) -> Backend {
    let resolv = sandbox.read_link("/etc/resolv.conf").unwrap_or_default();
    if resolv.contains("systemd/resolve") && sandbox.exists("/run/systemd/resolve") {
        return Backend::Resolved;
    }
    if !sandbox.exists("/run/NetworkManager") {
        return Backend::Unsupported(NOT_SUPPORTED);
    }
    match network_manager(sandbox, &resolv) {
        Ok(()) => Backend::NetworkManager,
        Err(reason) => Backend::Unsupported(reason),
    }
}

/// Whether a global DNS drop-in of IbexWall's own would take effect here,
/// and undo cleanly: NetworkManager has to be the one writing
/// `/etc/resolv.conf`, and nobody else may have set global DNS.
fn network_manager(sandbox: &Sandbox, resolv_link: &str) -> Result<(), &'static str> {
    if !running(sandbox, "NetworkManager.service") {
        return Err("NetworkManager is not running, and nothing else here is supported yet");
    }
    let written_by_it = if resolv_link.is_empty() {
        sandbox.read("/etc/resolv.conf").is_some_and(|text| {
            text.lines()
                .any(|line| line.trim() == "# Generated by NetworkManager")
        })
    } else {
        resolv_link.ends_with("NetworkManager/resolv.conf")
            || resolv_link.ends_with("NetworkManager/no-stub-resolv.conf")
    };
    if !written_by_it {
        return Err("NetworkManager does not write /etc/resolv.conf on this computer");
    }
    let config = Config::read(sandbox);
    match config.main.get("dns").map(String::as_str) {
        None | Some("" | "default") => {}
        Some("dnsmasq") => {
            return Err("NetworkManager is set to use dnsmasq (dns=dnsmasq), not supported yet");
        }
        Some(_) => {
            return Err("NetworkManager has a `dns=` setting that is not supported yet");
        }
    }
    if !matches!(
        config.main.get("rc-manager").map(String::as_str),
        None | Some("" | "auto" | "symlink" | "file" | "none")
    ) {
        return Err("NetworkManager is told not to manage /etc/resolv.conf itself (rc-manager)");
    }
    if config.global_dns {
        return Err("NetworkManager already has a global DNS setting that is not IbexWall's");
    }
    Ok(())
}

/// The part of NetworkManager's configuration that decides whether the
/// drop-in works, merged in the order NetworkManager.conf(5) documents.
#[derive(Default)]
struct Config {
    main: BTreeMap<String, String>,
    /// A `global-dns` section in any file other than IbexWall's.
    global_dns: bool,
}

impl Config {
    fn read(sandbox: &Sandbox) -> Self {
        const ETC: &str = "/etc/NetworkManager/conf.d";
        const RUN: &str = "/run/NetworkManager/conf.d";
        const LIB: &str = "/usr/lib/NetworkManager/conf.d";
        let names_in = |dir: &str| -> Vec<String> {
            sandbox
                .list(dir)
                .into_iter()
                .filter(|name| name.ends_with(".conf"))
                .collect()
        };
        let (etc, run, lib) = (names_in(ETC), names_in(RUN), names_in(LIB));
        // A file shadows one of the same name in a directory below it.
        let mut files: Vec<String> = lib
            .iter()
            .filter(|name| !etc.contains(name) && !run.contains(name))
            .map(|name| format!("{LIB}/{name}"))
            .collect();
        files.extend(
            run.iter()
                .filter(|name| !etc.contains(name))
                .map(|name| format!("{RUN}/{name}")),
        );
        files.push("/etc/NetworkManager/NetworkManager.conf".into());
        files.extend(etc.iter().map(|name| format!("{ETC}/{name}")));
        files.push("/var/lib/NetworkManager/NetworkManager-intern.conf".into());

        let mut config = Self::default();
        for file in files.iter().filter(|f| *f != names::ARTIFACT_NM_DNS) {
            let Some(text) = sandbox.read(file) else {
                continue;
            };
            let mut section = "";
            for line in text.lines().map(str::trim) {
                if let Some(name) = line.strip_prefix('[').and_then(|l| l.strip_suffix(']')) {
                    section = name;
                    config.global_dns |=
                        name.starts_with("global-dns") || name.starts_with(".intern.global-dns");
                } else if section == "main"
                    && !line.starts_with('#')
                    && let Some((key, value)) = line.split_once('=')
                {
                    config.main.insert(
                        key.trim().to_ascii_lowercase(),
                        value.trim().to_ascii_lowercase(),
                    );
                }
            }
        }
        config
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::symlink;

    fn root(name: &str) -> std::path::PathBuf {
        let root = std::env::temp_dir().join(format!("ibx-dnsbe-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("etc")).unwrap();
        root
    }

    fn put(root: &std::path::Path, path: &str, text: &str) {
        let full = root.join(path.trim_start_matches('/'));
        std::fs::create_dir_all(full.parent().unwrap()).unwrap();
        std::fs::write(full, text).unwrap();
    }

    /// A machine where NetworkManager runs and writes `resolv.conf`.
    fn network_manager_machine(name: &str) -> std::path::PathBuf {
        let root = root(name);
        put(
            &root,
            "/etc/resolv.conf",
            "# Generated by NetworkManager\nnameserver 192.0.2.1\n",
        );
        std::fs::create_dir_all(root.join("run/NetworkManager")).unwrap();
        std::fs::create_dir_all(root.join("run/systemd/units")).unwrap();
        symlink(
            "0123",
            root.join("run/systemd/units/invocation:NetworkManager.service"),
        )
        .unwrap();
        put(
            &root,
            "/etc/NetworkManager/NetworkManager.conf",
            "[main]\n# dns=dnsmasq\n[connectivity]\nuri=http://example.org/\n",
        );
        root
    }

    fn reason(root: &std::path::Path) -> &'static str {
        match detect(&Sandbox::at(root)) {
            Backend::Unsupported(reason) => reason,
            other => panic!("expected unsupported, got {other:?}"),
        }
    }

    #[test]
    fn detects_resolved_by_the_resolv_conf_symlink() {
        let root = root("resolved");
        std::fs::create_dir_all(root.join("run/systemd/resolve")).unwrap();
        symlink(
            "../run/systemd/resolve/stub-resolv.conf",
            root.join("etc/resolv.conf"),
        )
        .unwrap();
        assert_eq!(detect(&Sandbox::at(&root)), Backend::Resolved);
    }

    #[test]
    fn a_plain_resolv_conf_is_not_resolved() {
        let root = root("plain");
        std::fs::write(root.join("etc/resolv.conf"), "nameserver 192.0.2.1\n").unwrap();
        assert!(matches!(
            detect(&Sandbox::at(&root)),
            Backend::Unsupported(_)
        ));
    }

    #[test]
    fn a_networkmanager_that_is_not_running_is_reported_specifically() {
        let root = root("nm");
        std::fs::create_dir_all(root.join("run/NetworkManager")).unwrap();
        assert!(reason(&root).contains("NetworkManager"));
    }

    #[test]
    fn networkmanager_writing_resolv_conf_is_supported() {
        let root = network_manager_machine("nm-ok");
        assert_eq!(detect(&Sandbox::at(&root)), Backend::NetworkManager);
        // Its own run copy, linked, is the other documented way.
        std::fs::remove_file(root.join("etc/resolv.conf")).unwrap();
        symlink(
            "/run/NetworkManager/resolv.conf",
            root.join("etc/resolv.conf"),
        )
        .unwrap();
        assert_eq!(detect(&Sandbox::at(&root)), Backend::NetworkManager);
        // IbexWall's own drop-in does not count as somebody else's.
        put(
            &root,
            names::ARTIFACT_NM_DNS,
            "[global-dns]\n[global-dns-domain-*]\nservers=127.0.0.153\n",
        );
        assert_eq!(detect(&Sandbox::at(&root)), Backend::NetworkManager);
    }

    #[test]
    fn a_resolv_conf_somebody_else_writes_is_refused() {
        let root = network_manager_machine("nm-static");
        put(&root, "/etc/resolv.conf", "nameserver 192.0.2.1\n");
        assert!(reason(&root).contains("resolv.conf"));
        std::fs::remove_file(root.join("etc/resolv.conf")).unwrap();
        symlink("/run/resolvconf/resolv.conf", root.join("etc/resolv.conf")).unwrap();
        assert!(reason(&root).contains("resolv.conf"));
    }

    #[test]
    fn settings_that_would_ignore_the_dropin_are_refused() {
        for (name, text, expected) in [
            ("dnsmasq", "[main]\ndns=dnsmasq\n", "dnsmasq"),
            ("none", "[main]\ndns = none\n", "dns="),
            ("resolved", "[main]\ndns=systemd-resolved\n", "dns="),
            ("unmanaged", "[main]\nrc-manager=unmanaged\n", "rc-manager"),
            (
                "resolvconf",
                "[main]\nrc-manager=resolvconf\n",
                "rc-manager",
            ),
            (
                "global",
                "[global-dns-domain-*]\nservers=192.0.2.2\n",
                "global DNS",
            ),
        ] {
            let root = network_manager_machine(&format!("nm-{name}"));
            put(&root, "/etc/NetworkManager/conf.d/90-local.conf", text);
            assert!(
                reason(&root).contains(expected),
                "{name}: {}",
                reason(&root)
            );
        }
    }

    #[test]
    fn files_override_and_shadow_each_other_as_documented() {
        let root = network_manager_machine("nm-order");
        // The administrator's file wins over the package's.
        put(
            &root,
            "/usr/lib/NetworkManager/conf.d/10-dns.conf",
            "[main]\ndns=dnsmasq\n",
        );
        put(
            &root,
            "/etc/NetworkManager/conf.d/20-dns.conf",
            "[main]\ndns=default\n",
        );
        assert_eq!(detect(&Sandbox::at(&root)), Backend::NetworkManager);
        // A file of the same name replaces the package's one altogether.
        put(
            &root,
            "/usr/lib/NetworkManager/conf.d/30-global.conf",
            "[global-dns]\n",
        );
        put(&root, "/etc/NetworkManager/conf.d/30-global.conf", "");
        assert_eq!(detect(&Sandbox::at(&root)), Backend::NetworkManager);
        // What was set over D-Bus is read last.
        put(
            &root,
            "/var/lib/NetworkManager/NetworkManager-intern.conf",
            "[.intern.global-dns-domain-*]\nservers=192.0.2.2\n",
        );
        assert!(reason(&root).contains("global DNS"));
    }
}

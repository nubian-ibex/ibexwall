// Generates src/gen/contracts.ts from ../spec/schemas (the contract files
// exported by `cargo xtask schemas`). Never edit the output by hand.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { compile } from 'json-schema-to-typescript';

const dir = new URL('../../spec/schemas/', import.meta.url);
const definitions = {};

const rewrite = (node) => {
  if (Array.isArray(node)) return node.map(rewrite);
  if (node && typeof node === 'object') {
    return Object.fromEntries(
      Object.entries(node).map(([key, value]) => [
        key,
        key === '$ref' && typeof value === 'string'
          ? value.replace('#/$defs/', '#/definitions/')
          : rewrite(value),
      ]),
    );
  }
  return node;
};

for (const file of readdirSync(dir)
  .filter((f) => f.endsWith('.schema.json'))
  .sort()) {
  const schema = JSON.parse(readFileSync(new URL(file, dir), 'utf8'));
  const name = schema.title ?? file.replace('.schema.json', '');
  const { $defs = {}, ...body } = schema;
  delete body.$schema;
  for (const [defName, def] of Object.entries($defs)) {
    definitions[defName] ??= rewrite(def);
  }
  definitions[name] = rewrite(body);
}

const names = Object.keys(definitions).sort();
const root = {
  title: 'AllContracts',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/definitions/${n}` }])),
  definitions,
};

const banner =
  '// GENERATED by scripts/gen-types.mjs from spec/schemas. Do not edit.\n' +
  '// SPDX-License-Identifier: Apache-2.0 OR MIT\n';
const ts = await compile(root, 'AllContracts', {
  bannerComment: banner,
  additionalProperties: false,
  style: { singleQuote: true },
});
writeFileSync(new URL('../src/gen/contracts.ts', import.meta.url), ts);
console.log(`wrote src/gen/contracts.ts (${names.length} types)`);
